import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import ts from "typescript";
import { PGlite } from "@electric-sql/pglite";
import bcrypt from "bcryptjs";
import crypto from "node:crypto";

const read = (path) =>
  readFileSync(fileURLToPath(new URL(`../${path}`, import.meta.url)), "utf8");

function loadModule(relativePath, mocks = {}) {
  const code = read(relativePath);
  const transpiled = ts.transpileModule(code, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  }).outputText;

  const exports = {};
  const moduleObj = { exports };
  const customRequire = (name) => {
    if (mocks[name]) return mocks[name];
    if (name === "bcryptjs") return { default: bcrypt, ...bcrypt };
    if (name === "crypto" || name === "node:crypto")
      return { default: crypto, ...crypto };
    if (name === "server-only") return {};
    if (name === "next/headers") {
      return {
        cookies: async () => ({
          get: () => undefined,
          set: () => {},
        }),
      };
    }
    return {};
  };

  vm.runInNewContext(transpiled, {
    exports,
    module: moduleObj,
    require: customRequire,
    console,
    crypto,
    Buffer,
    process,
    Date,
    Math,
  });

  return moduleObj.exports;
}

const passwordsMod = loadModule("lib/auth/passwords.ts");
const sessionMod = loadModule("lib/auth/session.ts");
const qbMod = loadModule("lib/db/query-builder.ts");

test("passwords_bcryptVerification_authenticatesValidPasswordAndRejectsWrong", async () => {
  const plainPassword = "TestPassword123!";
  const hash = await passwordsMod.hashPassword(plainPassword);

  assert.match(hash, /^\$2[ab]\$10\$/);
  assert.equal(await passwordsMod.verifyPassword(plainPassword, hash), true);
  assert.equal(
    await passwordsMod.verifyPassword("WrongPassword!", hash),
    false,
  );
  assert.equal(await passwordsMod.verifyPassword("", hash), false);
});

test("passwords_supabaseBcryptHash_isFullyCompatibleWithoutReset", async () => {
  // Typical bcrypt hash generated by Supabase GoTrue / Go bcrypt (cost 10)
  // Password: "Password123!"
  const supabaseSampleHash =
    "$2b$10$xS49stQh43mrSIdAU.EJ4.zEcN8/Ybgyzic.ThAghGKkfPfLLa2Xe";
  assert.equal(supabaseSampleHash.startsWith("$2b$10$"), true);
  assert.equal(
    await passwordsMod.verifyPassword("Password123!", supabaseSampleHash),
    true,
  );
  assert.equal(
    await passwordsMod.verifyPassword("WrongPassword!", supabaseSampleHash),
    false,
  );
});

test("session_tokenSigningAndVerification_preservesPayloadAndDetectsTampering", () => {
  process.env.AUTH_SESSION_SECRET =
    "test-secret-key-32-characters-minimum-for-testing";
  const userId = "11111111-2222-3333-4444-555555555555";
  const username = "testuser";

  const token = sessionMod.signToken({ sub: userId, username });
  assert.equal(typeof token, "string");
  assert.equal(token.split(".").length, 3);

  const payload = sessionMod.verifyToken(token);
  assert.notEqual(payload, null);
  assert.equal(payload.sub, userId);
  assert.equal(payload.username, username);

  // Tampered token
  const tamperedToken = token.slice(0, -5) + "abcde";
  assert.equal(sessionMod.verifyToken(tamperedToken), null);

  // Expired token
  const expiredToken = sessionMod.signToken({
    sub: userId,
    exp: Math.floor(Date.now() / 1000) - 10,
  });
  assert.equal(sessionMod.verifyToken(expiredToken), null);
});

test("queryBuilder_parameterizedQueries_executeSafelyOnPostgres", async () => {
  const db = new PGlite();
  await db.exec(`
    create table test_items (
      id uuid primary key,
      organization_id uuid not null,
      name text not null,
      price numeric not null,
      created_at timestamptz default now()
    );
  `);

  const qb = new qbMod.QueryBuilder("test_items", db);
  const itemId = "12345678-1234-1234-1234-123456789012";
  const orgId = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa";

  // Insert
  const insertRes = await qb.insert({
    id: itemId,
    organization_id: orgId,
    name: "Room 101",
    price: 3500,
  });
  assert.equal(insertRes.error, null);
  assert.equal(insertRes.data.length, 1);
  assert.equal(insertRes.data[0].name, "Room 101");

  // Select with eq
  const selectRes = await new qbMod.QueryBuilder("test_items", db)
    .select("id, name, price")
    .eq("organization_id", orgId)
    .eq("id", itemId)
    .maybeSingle();

  assert.equal(selectRes.error, null);
  assert.equal(selectRes.data.name, "Room 101");
  assert.equal(Number(selectRes.data.price), 3500);

  // Update
  const updateRes = await new qbMod.QueryBuilder("test_items", db)
    .update({ name: "Room 101 Deluxe" })
    .eq("id", itemId)
    .eq("organization_id", orgId);

  assert.equal(updateRes.error, null);
  assert.equal(updateRes.data[0].name, "Room 101 Deluxe");

  // Delete
  const deleteRes = await new qbMod.QueryBuilder("test_items", db)
    .delete()
    .eq("id", itemId);

  assert.equal(deleteRes.error, null);
  assert.equal(deleteRes.data.length, 1);

  await db.close();
});

test("crossTenantIsolation_userCannotAccessOtherOrganizationResources", async () => {
  const db = new PGlite();
  await db.exec(`
    create table tenant_resources (
      id uuid primary key,
      organization_id uuid not null,
      title text not null
    );
  `);

  const orgA = "11111111-1111-1111-1111-111111111111";
  const orgB = "22222222-2222-2222-2222-222222222222";
  const resourceB = "bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb";

  // Insert resource belonging to Org B
  await new qbMod.QueryBuilder("tenant_resources", db).insert({
    id: resourceB,
    organization_id: orgB,
    title: "Org B Secret Financial Data",
  });

  // User in Org A attempts to select Org B's resource using direct ID
  const crossSelect = await new qbMod.QueryBuilder("tenant_resources", db)
    .select("*")
    .eq("id", resourceB)
    .eq("organization_id", orgA) // Enforced by server action context
    .maybeSingle();

  assert.equal(crossSelect.error, null);
  assert.equal(crossSelect.data, null); // Denied / Not found

  // User in Org A attempts to update Org B's resource
  const crossUpdate = await new qbMod.QueryBuilder("tenant_resources", db)
    .update({ title: "Hacked by Org A" })
    .eq("id", resourceB)
    .eq("organization_id", orgA);

  assert.equal(crossUpdate.error, null);
  assert.equal(crossUpdate.data.length, 0); // No rows affected

  // Verify resource in Org B remains unchanged
  const verifyB = await new qbMod.QueryBuilder("tenant_resources", db)
    .select("*")
    .eq("id", resourceB)
    .eq("organization_id", orgB)
    .maybeSingle();

  assert.equal(verifyB.data.title, "Org B Secret Financial Data");

  await db.close();
});

test("atomicTransactions_rollsBackCompletelyOnFailure", async () => {
  const db = new PGlite();
  await db.exec(`
    create table accounts (id text primary key, balance int);
    insert into accounts values ('A', 1000), ('B', 500);
  `);

  try {
    // Simulate multi-step transfer transaction
    await db.exec("BEGIN");
    await db.query(
      "UPDATE accounts SET balance = balance - 200 WHERE id = 'A'",
    );
    // Simulate unexpected crash/error in step 2
    throw new Error("Simulated failure in transaction");
    await db.query(
      "UPDATE accounts SET balance = balance + 200 WHERE id = 'B'",
    );
    await db.exec("COMMIT");
  } catch {
    await db.exec("ROLLBACK");
  }

  // Verify rollback preserved balances
  const { rows } = await db.query(
    "SELECT id, balance FROM accounts ORDER BY id",
  );
  assert.equal(rows[0].balance, 1000);
  assert.equal(rows[1].balance, 500);

  await db.close();
});
